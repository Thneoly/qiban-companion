// Isolated native UI acceptance: real window sizing/IPC, synthetic local model only.
const { Harness, delay } = require('./q6/harness.cjs');
const { expect } = require('@playwright/test');
const { DatabaseSync } = require('node:sqlite');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const h = new Harness();
  try {
    await h.setup();
    await h.invoke(h.pet, 'guide_complete');
    await h.model(h.base, 'ui-fixture');
    const size = () => h.pet.evaluate(() => ({width:innerWidth,height:innerHeight}));
    await expect.poll(size).toEqual({width:320,height:440});
    await delay(1300);
    const position = () => { const db = new DatabaseSync(path.join(h.directory,'desktop-settings.db'),{readOnly:true}); try {return db.prepare('SELECT x,y FROM pet_position WHERE id=1').get();} finally {db.close();} };
    const originalPosition = position();
    await h.invoke(h.pet,'pet_action',{action:'open_panel'});
    await h.panel.getByLabel('任务标题',{exact:true}).fill('导航保留的草稿');
    await h.invoke(h.pet,'pet_action',{action:'open_settings'});
    await expect(h.panel.getByLabel('设置空间',{exact:true})).toBeVisible();
    await h.invoke(h.pet,'pet_action',{action:'open_memory'});
    await expect(h.panel.getByLabel('记忆空间',{exact:true})).toBeVisible();
    await h.panel.getByRole('link',{name:'日常',exact:true}).click();
    await expect(h.panel.getByLabel('任务标题',{exact:true})).toHaveValue('导航保留的草稿');
    await h.panel.getByRole('button',{name:'打开文字对话 ↗'}).click();
    await expect.poll(size).toEqual({width:760,height:720});
    await expect(h.pet.getByRole('region',{name:'对话阅读区'})).toBeVisible();
    const input = h.pet.getByLabel('和栖栖说句话');
    await input.fill('Q6_HOLD');
    await input.press('Enter');
    await expect.poll(()=>h.requests.length).toBe(1);
    await h.invoke(h.pet,'pet_action',{action:'open_settings'});
    await expect(input).toBeVisible();
    await h.pet.getByRole('button',{name:'收回气泡',exact:true}).click();
    await expect.poll(size).toEqual({width:320,height:440});
    await expect(input).toHaveValue('Q6_HOLD');
    await h.pet.getByRole('button',{name:'展开阅读',exact:true}).click();
    await expect.poll(size).toEqual({width:760,height:720});
    h.release();
    await expect(h.pet.locator('.chat-phase')).toHaveText('已完成');
    assert.equal(h.requests.length,1,'Resizing must not resend');
    await h.pet.screenshot({path:path.join(h.evidence,'conversation-native.png')});
    await delay(1300);
    assert.deepEqual(position(),originalPosition,'Wide window must not overwrite pet position');
    await h.pet.getByRole('button',{name:'收起气泡',exact:true}).click();
    await expect.poll(size).toEqual({width:320,height:440});
    await delay(1300);
    assert.deepEqual(position(),originalPosition);
    await h.restart();
    await expect.poll(size).toEqual({width:320,height:440});
    assert.deepEqual(position(),originalPosition);
    await h.invoke(h.pet,'pet_action',{action:'open_chat'});
    await expect.poll(size).toEqual({width:760,height:720});
    await expect(h.pet.getByRole('region',{name:'对话阅读区'})).toContainText('Q6_HOLD');
    h.write('conversation-space.json',{checks:['native-navigation','draft-preserved','760x720-expand','blur-preserved','single-request-across-resize','320x440-collapse','pet-position-preserved','restart-history'],requests:h.requests.length,sourceDirty:h.meta.sourceDirty});
    console.log('PASS: native conversation sizing, navigation, live stream, position and restart. Evidence: '+h.evidence);
  } finally {await h.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
